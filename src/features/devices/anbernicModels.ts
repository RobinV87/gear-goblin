export const anbernicModels = Object.keys(anbernicCatalog)

export function getAnbernicSpecs(manufacturer: string, model: string): HandheldSpecs | undefined {
  if (manufacturer.trim().toLowerCase() !== 'anbernic') return undefined
  const normalize = (value: string) => value.toLowerCase().replace(/\s+/g, '')
  const match = anbernicModels.find(option => normalize(option) === normalize(model))
  return match ? anbernicCatalog[match] : undefined
}
